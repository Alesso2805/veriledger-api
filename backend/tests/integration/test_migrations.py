BACKEND = Path(__file__).resolve().parents[2]

# Sync tests: alembic's env.py runs the migrations with asyncio.run, which cannot start inside a running loop.


def run_sql(*statements: str) -> list[list[str]]:
    async def run() -> list[list[str]]:
        engine = create_async_engine(TEST_DATABASE_URL, poolclass=NullPool)
        results = []
        async with engine.begin() as conn:
            for sql in statements:
                result = await conn.execute(text(sql))
                results.append([row[0] for row in result.all()] if result.returns_rows else [])
        await engine.dispose()
        return results

    return asyncio.run(run())


@pytest.fixture
def alembic_config(monkeypatch: pytest.MonkeyPatch) -> Generator[Config, None, None]:
    if not TEST_DATABASE_URL.startswith("postgresql"):
        pytest.skip("needs TEST_DATABASE_URL pointing to a throwaway PostgreSQL")
    # env.py takes its URL from the settings, so they point at the throwaway database
    monkeypatch.setattr(settings, "database_url", TEST_DATABASE_URL)
    config = Config()
    config.set_main_option("script_location", str(BACKEND / "alembic"))
    run_sql("DROP SCHEMA public CASCADE", "CREATE SCHEMA public")
    yield config
    run_sql("DROP SCHEMA public CASCADE", "CREATE SCHEMA public")


def leftovers() -> list[list[str]]:
    return run_sql(
        "SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename <> 'alembic_version'",
        "SELECT t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace"
        " WHERE n.nspname = 'public' AND t.typtype = 'e'",
    )


def test_ar06_the_models_and_the_migration_history_describe_the_same_schema(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    # Raises AutogenerateDiffsDetected if the models and the migrations disagree
    command.check(alembic_config)


def test_ar07_the_migrations_go_down_to_base_and_up_again_leaving_nothing_behind(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")
    assert leftovers() == [[], []]
    command.upgrade(alembic_config, "head")


@pytest.mark.parametrize("column", ["amount", "fee"])
def test_the_migrated_schema_refuses_a_negative_amount_or_fee(alembic_config: Config, column: str) -> None:
    command.upgrade(alembic_config, "head")
    values = {"amount": "1", "fee": "0", column: "-0.00000001"}

    with pytest.raises(IntegrityError, match=f"ck_transactions_{column}_not_negative"):
        run_sql(
            "INSERT INTO transactions (id, sender_address, receiver_address, amount, fee, status, timestamp, signature)"
            f" VALUES ('t', 'a', 'b', {values['amount']}, {values['fee']}, 'PENDING', now(), 'sig')"
        )
